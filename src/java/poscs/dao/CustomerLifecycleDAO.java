package poscs.dao;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import poscs.model.CustomerLifecycleEvent;
import poscs.model.RelationshipRating;
import poscs.model.User;

/**
 * Data Access Object chuyên biệt cho đánh giá & sự kiện vòng đời khách hàng
 * (Customer Lifecycle Events & Evaluations - bảng customer_lifecycle_events).
 *
 * <p>Tách từ {@link CustomerDAO} (Task 2.3) nhằm phân tách rõ ràng trách nhiệm:
 * <ul>
 *   <li>Quản lý lịch sử các sự kiện vòng đời của doanh nghiệp (customer_lifecycle_events).</li>
 *   <li>Thực hiện cập nhật xếp hạng quan hệ (enterprises.current_relationship_rating)
 *       đồng thời ghi nhật ký sự kiện trong cùng một transaction toàn vẹn.</li>
 * </ul>
 */
public class CustomerLifecycleDAO {

    private static final Logger LOG = LoggerFactory.getLogger(CustomerLifecycleDAO.class);

    /**
     * Ghi 1 sự kiện mới vào bảng customer_lifecycle_events.
     *
     * @param event thông tin sự kiện vòng đời cần ghi
     * @return event_id vừa sinh, hoặc -1 nếu thất bại
     */
    public int insertLifecycleEvent(CustomerLifecycleEvent event) {
        if (event == null || event.getEnterpriseId() <= 0 || event.getRelationshipRating() == null
                || event.getRecordedBy() <= 0 || event.getEventDate() == null) {
            return -1;
        }
        try (Connection conn = DBContext.getConnection()) {
            return insertLifecycleEvent(conn, event);
        } catch (SQLException ex) {
            LOG.error("Loi ghi lich su danh gia khach hang (enterpriseId={})", event.getEnterpriseId(), ex);
            return -1;
        }
    }

    /**
     * Một lần đánh giá xếp hạng THỦ CÔNG: cập nhật
     * {@code enterprises.current_relationship_rating} VÀ ghi dòng lịch sử vào
     * {@code customer_lifecycle_events}, trong CÙNG một transaction toàn vẹn.
     *
     * <p>Nếu khách hàng đã bị xoá mềm (ở tab khác) hoặc không tồn tại thì câu
     * lệnh UPDATE không chạm dòng nào -- coi là thất bại, rollback toàn bộ và
     * không ghi lịch sử mồ côi.
     *
     * @param event thông tin sự kiện đánh giá (chứa enterpriseId, relationshipRating, recordedBy, v.v.)
     * @return true nếu đã cập nhật xếp hạng và ghi dòng lịch sử thành công
     */
    public boolean recordEvaluation(CustomerLifecycleEvent event) {
        if (event == null || event.getEnterpriseId() <= 0 || event.getRelationshipRating() == null
                || event.getRecordedBy() <= 0 || event.getEventDate() == null) {
            return false;
        }
        try (Connection conn = DBContext.getConnection()) {
            conn.setAutoCommit(false);
            boolean committed = false;
            try {
                try (PreparedStatement ps = conn.prepareStatement(
                        "UPDATE enterprises SET current_relationship_rating = ? "
                        + "WHERE enterprise_id = ? AND is_deleted = 0")) {
                    ps.setString(1, event.getRelationshipRating().getDbValue());
                    ps.setInt(2, event.getEnterpriseId());
                    if (ps.executeUpdate() == 0) {
                        return false;
                    }
                }
                if (insertLifecycleEvent(conn, event) <= 0) {
                    return false;
                }
                conn.commit();
                committed = true;
                return true;
            } finally {
                if (!committed) {
                    conn.rollback();
                }
                conn.setAutoCommit(true);
            }
        } catch (SQLException ex) {
            LOG.error("Loi ghi danh gia xep hang khach hang (enterpriseId={})", event.getEnterpriseId(), ex);
            return false;
        }
    }

    /**
     * Helper thực thi câu lệnh INSERT vào customer_lifecycle_events trên Connection đang mở.
     * Dùng chung cho cả phương thức đơn lẻ lẫn transaction gộp trong recordEvaluation.
     */
    private int insertLifecycleEvent(Connection conn, CustomerLifecycleEvent event) throws SQLException {
        String sql = "INSERT INTO customer_lifecycle_events " +
                "(enterprise_id, event_type, relationship_rating, is_auto_generated, description, event_date, recorded_by) " +
                "VALUES (?, ?, ?, ?, ?, ?, ?)";
        try (PreparedStatement ps = conn.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            ps.setInt(1, event.getEnterpriseId());
            ps.setString(2, event.getEventType());
            ps.setString(3, event.getRelationshipRating() != null ? event.getRelationshipRating().getDbValue() : null);
            ps.setBoolean(4, event.isAutoGenerated());
            ps.setString(5, event.getDescription());
            ps.setDate(6, event.getEventDate());
            ps.setInt(7, event.getRecordedBy());

            int affected = ps.executeUpdate();
            if (affected == 0) {
                return -1;
            }
            try (ResultSet keys = ps.getGeneratedKeys()) {
                return keys.next() ? keys.getInt(1) : -1;
            }
        }
    }

    /**
     * Lấy toàn bộ lịch sử đánh giá vòng đời của 1 khách hàng theo enterprise_id,
     * sắp xếp mới nhất trước (event_date DESC, event_id DESC), kèm thông tin người ghi nhận.
     *
     * @param enterpriseId ID khách hàng doanh nghiệp
     * @return danh sách các sự kiện vòng đời (không bao giờ trả về null)
     */
    public List<CustomerLifecycleEvent> findLifecycleEventsByEnterpriseId(int enterpriseId) {
        List<CustomerLifecycleEvent> result = new ArrayList<>();
        if (enterpriseId <= 0) {
            return result;
        }
        String sql = "SELECT ev.event_id, ev.enterprise_id, ev.event_type, ev.relationship_rating, " +
                "       ev.is_auto_generated, ev.description, ev.event_date, ev.recorded_by, ev.created_at, " +
                "       u.last_name AS recorder_last_name, u.middle_name AS recorder_middle_name, " +
                "       u.first_name AS recorder_first_name " +
                "FROM customer_lifecycle_events ev " +
                "JOIN users u ON u.user_id = ev.recorded_by " +
                "WHERE ev.enterprise_id = ? " +
                "ORDER BY ev.event_date DESC, ev.event_id DESC";
        try (Connection conn = DBContext.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setInt(1, enterpriseId);
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    CustomerLifecycleEvent ev = new CustomerLifecycleEvent();
                    ev.setEventId(rs.getInt("event_id"));
                    ev.setEnterpriseId(rs.getInt("enterprise_id"));
                    ev.setEventType(rs.getString("event_type"));
                    ev.setRelationshipRating(RelationshipRating.fromDbValue(rs.getString("relationship_rating")));
                    ev.setAutoGenerated(rs.getBoolean("is_auto_generated"));
                    ev.setDescription(rs.getString("description"));
                    ev.setEventDate(rs.getDate("event_date"));
                    ev.setRecordedBy(rs.getInt("recorded_by"));
                    ev.setCreatedAt(rs.getTimestamp("created_at"));

                    User recorder = new User();
                    recorder.setLastName(rs.getString("recorder_last_name"));
                    recorder.setMiddleName(rs.getString("recorder_middle_name"));
                    recorder.setFirstName(rs.getString("recorder_first_name"));
                    ev.setRecordedByUser(recorder);

                    result.add(ev);
                }
            }
        } catch (SQLException ex) {
            LOG.error("Loi doc lich su danh gia khach hang (enterpriseId={})", enterpriseId, ex);
        }
        return result;
    }

    /**
     * Alias ngắn gọn cho {@link #findLifecycleEventsByEnterpriseId(int)}.
     *
     * @param enterpriseId ID khách hàng doanh nghiệp
     * @return danh sách các sự kiện vòng đời
     */
    public List<CustomerLifecycleEvent> findByEnterpriseId(int enterpriseId) {
        return findLifecycleEventsByEnterpriseId(enterpriseId);
    }
}
