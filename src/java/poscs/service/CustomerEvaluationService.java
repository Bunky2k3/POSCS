package poscs.service;

import java.sql.Date;
import java.time.LocalDate;
import java.util.Collections;
import java.util.List;
import poscs.dao.AddressDAO;
import poscs.dao.CustomerDAO;
import poscs.dao.EmployeeDAO;
import poscs.model.CustomerLifecycleEvent;
import poscs.model.Enterprise;
import poscs.model.RelationshipRating;
import poscs.model.User;

/**
 * Service quản lý đánh giá vòng đời khách hàng và lịch sử xếp hạng quan hệ
 * (Customer Lifecycle Evaluation & Events).
 *
 * <p>Quy tắc nghiệp vụ:
 * <ul>
 *   <li>Đánh giá xếp hạng quan hệ thủ công theo 4 mức (GOOD, NEEDS_REVIEW, BAD, AT_RISK).</li>
 *   <li>Kiểm tra quyền ghi theo địa bàn của Sales trước khi cho phép đánh giá.</li>
 *   <li>Ghi nhận đồng bộ xếp hạng hiện tại và lịch sử sự kiện trong cùng một transaction.</li>
 * </ul>
 *
 * <p>Không phụ thuộc vào Servlet API.
 */
public class CustomerEvaluationService extends BaseService {

    private final CustomerDAO customerDAO;
    private final CustomerService customerService;

    public CustomerEvaluationService() {
        this(new CustomerDAO(), new CustomerService());
    }

    public CustomerEvaluationService(CustomerDAO customerDAO, CustomerService customerService) {
        this.customerDAO = customerDAO;
        this.customerService = customerService;
    }

    public CustomerEvaluationService(CustomerDAO customerDAO, EmployeeDAO employeeDAO, AddressDAO addressDAO) {
        this(customerDAO, new CustomerService(customerDAO, employeeDAO, addressDAO));
    }

    /**
     * Parse chuỗi rating sang enum RelationshipRating.
     * Chấp nhận tên enum (GOOD, NEEDS_REVIEW, BAD, AT_RISK) hoặc giá trị tiếng Việt trong DB
     * (Tốt, Cần theo dõi, Xấu, Có nguy cơ rời bỏ). Trả về null nếu không hợp lệ.
     */
    public RelationshipRating parseRatingOrNull(String value) {
        if (value == null || value.trim().isEmpty()) {
            return null;
        }
        String trimmed = value.trim();
        try {
            return RelationshipRating.valueOf(trimmed);
        } catch (IllegalArgumentException ex) {
            return RelationshipRating.fromDbValue(trimmed);
        }
    }

    /**
     * Thực hiện đánh giá xếp hạng quan hệ khách hàng.
     *
     * @param customerId mã định danh khách hàng
     * @param ratingStr tên enum hoặc giá trị tiếng Việt của mức xếp hạng (GOOD, NEEDS_REVIEW, BAD, AT_RISK)
     * @param description ghi chú đánh giá
     * @param actor người dùng đang thực hiện đánh giá
     * @param isSales true nếu người thực hiện có vai trò Sales
     * @return ServiceResult chứa sự kiện vừa ghi nhận hoặc mã lỗi
     */
    public ServiceResult<CustomerLifecycleEvent> evaluateCustomer(int customerId, String ratingStr,
            String description, User actor, boolean isSales) {
        RelationshipRating rating = parseRatingOrNull(ratingStr);
        if (rating == null) {
            return failure("invalid_rating");
        }
        return evaluateCustomer(customerId, rating, description, actor, isSales);
    }

    /**
     * Thực hiện đánh giá xếp hạng quan hệ khách hàng với đối tượng enum RelationshipRating đã định kiểu.
     */
    public ServiceResult<CustomerLifecycleEvent> evaluateCustomer(int customerId, RelationshipRating rating,
            String description, User actor, boolean isSales) {
        if (actor == null || actor.getUserId() <= 0 || customerId <= 0) {
            return failure("invalid");
        }
        if (rating == null) {
            return failure("invalid_rating");
        }

        Enterprise existing = customerDAO.findById(customerId);
        if (existing == null) {
            return failure("notfound");
        }

        List<String> roles = customerDAO.findRolesOf(customerId);
        if (customerService.isOutsideSalesScope(existing, roles, actor, isSales)) {
            return failure("not_your_customer");
        }

        CustomerLifecycleEvent event = new CustomerLifecycleEvent();
        event.setEnterpriseId(customerId);
        event.setEventType("Đánh giá xếp hạng");
        event.setRelationshipRating(rating);
        event.setAutoGenerated(false);
        event.setDescription(description != null && !description.trim().isEmpty() ? description.trim() : null);
        event.setEventDate(Date.valueOf(LocalDate.now()));
        event.setRecordedBy(actor.getUserId());

        if (!customerDAO.recordEvaluation(event)) {
            log.warning("Danh gia khach hang that bai (actor=" + actor.getUserId() + ", enterpriseId=" + customerId + ")");
            return failure("evaluate_failed");
        }

        return success(event, "evaluated");
    }

    /**
     * Lấy toàn bộ lịch sử sự kiện đánh giá vòng đời của 1 khách hàng.
     */
    public List<CustomerLifecycleEvent> getLifecycleEvents(int customerId) {
        if (customerId <= 0) {
            return Collections.emptyList();
        }
        return customerDAO.findLifecycleEventsByEnterpriseId(customerId);
    }
}
