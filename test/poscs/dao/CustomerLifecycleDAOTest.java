    private final CustomerLifecycleDAO dao = new CustomerLifecycleDAO();

    private static CustomerLifecycleEvent sampleEvent() {
        CustomerLifecycleEvent e = new CustomerLifecycleEvent();
        e.setEnterpriseId(3);
        e.setEventType("Đánh giá định kỳ");
        e.setRelationshipRating(RelationshipRating.GOOD);
        e.setAutoGenerated(false);
        e.setDescription("Khách hàng hợp tác tốt");
        e.setEventDate(Date.valueOf("2026-09-09"));
        e.setRecordedBy(5);
        return e;
    }

